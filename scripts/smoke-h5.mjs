const text = (value) => page.getByText(value, { exact: true })
const button = (value) => page.getByRole('button', { name: value, exact: true })
const tab = (value) => page.getByRole('link', { name: value, exact: true })
const fieldSelector = (id) => `#${id} input, #${id} textarea`
const field = (id) => page.locator(fieldSelector(id))
const waitForFieldFocus = (id) => page.waitForFunction((selector) => document.activeElement === document.querySelector(selector), fieldSelector(id))
const confirmDialog = (name) => page.getByRole('alertdialog', { name, exact: true })
const waitForCancelFocus = () => page.waitForFunction(() => document.activeElement?.classList.contains('mobile-confirm__cancel'))

async function waitForFieldValue(id, value) {
  await page.waitForFunction(
    ({ selector, value }) => document.querySelector(selector)?.value === value,
    { selector: fieldSelector(id), value },
  )
}

async function noOverflow() {
  const dimensions = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth }))
  assert.ok(dimensions.scroll <= dimensions.width, JSON.stringify(dimensions))
}

async function choose(label, value) {
  await button(label).click()
  const dialog = page.getByRole('dialog', { name: label, exact: true })
  await dialog.getByRole('button', { name: value, exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
}

